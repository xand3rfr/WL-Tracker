function seeded(seed) {
  let s = seed >>> 0;
  return () => { s = (s + 0x6d2b79f5) | 0; let t = Math.imul(s ^ (s >>> 15), 1 | s); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
}

// generate with a fixed seed so every device builds identical presets
function withSeed(seed, fn) {
  const real = Math.random;
  Math.random = seeded(seed);
  try { return fn(); } finally { Math.random = real; }
}

let cache = null;
export function presetBuilds() {
  if (cache) return cache;
  cache = PRESETS.map(p => withSeed(p.seed, () => {
    let b = randomBuild();
    for (let i = 0; i < 300 && b.position !== p.pos; i++) b = randomBuild();
    b.position = p.pos;
    b.identity = { ...b.identity, first: p.first, last: p.last, nickname: p.nick, number: p.number };
    b.look.jersey = p.jersey;
    scaleToOvr(b, p.ovr);
    autoEquipBadges(b, overall(b));
    b.id = 'preset:' + p.seed;
    return b;
  }));
  return cache;
}

